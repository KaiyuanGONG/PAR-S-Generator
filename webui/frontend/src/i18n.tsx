export interface PreferenceStorage {
  getItem(key: string): string | null;
  setItem(key: string, value: string): void;
}

function safePreferenceStorage(): PreferenceStorage | null {
  try {
    return typeof window !== "undefined" ? window.localStorage : null;
  } catch {
    return null;
  }
}

function storedValue(storage: PreferenceStorage | null, key: string): string | null {
  try {
    return storage?.getItem(key) ?? null;
  } catch {
    return null;
  }
}

function saveValue(storage: PreferenceStorage | null, key: string, value: string): void {
  try {
    storage?.setItem(key, value);
  } catch {
    // Preferences are best-effort; a blocked localStorage must not block work.
  }
}

function localeFromLanguageTag(tag: string): Locale | null {
  const language = tag.trim().toLowerCase();
  if (language === "zh" || language.startsWith("zh-")) return "zh";
  if (language === "fr" || language.startsWith("fr-")) return "fr";
  if (language === "en" || language.startsWith("en-")) return "en";
  return null;
}

export function detectLocale(storage: PreferenceStorage | null = safePreferenceStorage()): Locale {
  const stored = storedValue(storage, LOCALE_STORAGE_KEY);
  const storedLocale = stored ? localeFromLanguageTag(stored) : null;
  if (storedLocale) return storedLocale;
  if (typeof navigator === "undefined") return "en";
  const languages = navigator.languages?.length ? navigator.languages : [navigator.language];
  for (const language of languages) {
    const locale = localeFromLanguageTag(language);
    if (locale) return locale;
  }
  return "en";
}

export function detectThemePreference(
  storage: PreferenceStorage | null = safePreferenceStorage(),
): ThemePreference {
  const stored = storedValue(storage, THEME_STORAGE_KEY);
  return stored === "light" || stored === "dark" || stored === "system" ? stored : "system";
}

function systemTheme(): ResolvedTheme {
  try {
    return typeof window !== "undefined" && window.matchMedia("(prefers-color-scheme: dark)").matches
      ? "dark"
      : "light";
  } catch {
    return "light";
  }
}

export interface I18nContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: Translate;
  themePreference: ThemePreference;
  setThemePreference: (theme: ThemePreference) => void;
  resolvedTheme: ResolvedTheme;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export interface I18nProviderProps {
  children: ReactNode;
  initialLocale?: Locale;
  initialTheme?: ThemePreference;
  storage?: PreferenceStorage | null;
}

export function I18nProvider({
  children,
  initialLocale,
  initialTheme,
  storage,
}: I18nProviderProps) {
  const targetStorage = storage === undefined ? safePreferenceStorage() : storage;
  const [locale, setLocale] = useState<Locale>(() => initialLocale ?? detectLocale(targetStorage));
  const [themePreference, setThemePreference] = useState<ThemePreference>(
    () => initialTheme ?? detectThemePreference(targetStorage),
  );
  const [systemPreference, setSystemPreference] = useState<ResolvedTheme>(systemTheme);

  useEffect(() => {
    saveValue(targetStorage, LOCALE_STORAGE_KEY, locale);
    if (typeof document !== "undefined") document.documentElement.lang = locale === "zh" ? "zh-CN" : locale;
  }, [locale, targetStorage]);

  useEffect(() => {
    saveValue(targetStorage, THEME_STORAGE_KEY, themePreference);
  }, [targetStorage, themePreference]);

  useEffect(() => {
    if (typeof window === "undefined") return;
    const query = window.matchMedia("(prefers-color-scheme: dark)");
    const update = () => setSystemPreference(query.matches ? "dark" : "light");
    update();
    query.addEventListener("change", update);
    return () => query.removeEventListener("change", update);
  }, []);

  const resolvedTheme = themePreference === "system" ? systemPreference : themePreference;

  useEffect(() => {
    if (typeof document === "undefined") return;
    document.documentElement.setAttribute("data-theme", resolvedTheme);
    document.documentElement.setAttribute("data-theme-preference", themePreference);
  }, [resolvedTheme, themePreference]);

  const t = useMemo<Translate>(
    () =>
      ((key: TranslationKey, variables?: InterpolationValues) =>
        interpolate(messages[locale][key] ?? en[key], variables)) as Translate,
    [locale],
  );
  const value = useMemo<I18nContextValue>(
    () => ({ locale, setLocale, t, themePreference, setThemePreference, resolvedTheme }),
    [locale, resolvedTheme, t, themePreference],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}
