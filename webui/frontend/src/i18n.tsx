type InterpolationValues = Record<string, string | number>;
type TranslationArgs<Key extends TranslationKey> = Key extends keyof TranslationVariables
  ? [variables: TranslationVariables[Key]]
  : [variables?: InterpolationValues];

export type Translate = <Key extends TranslationKey>(
  key: Key,
  ...args: TranslationArgs<Key>
) => string;

function interpolate(template: string, variables?: InterpolationValues): string {
  if (!variables) return template;
  return template.replace(/\{([A-Za-z0-9_]+)\}/g, (token, name: string) => {
    const value = variables[name];
    return value === undefined ? token : String(value);
  });
}

export function translate<Key extends TranslationKey>(
  locale: Locale,
  key: Key,
  ...args: TranslationArgs<Key>
): string {
  return interpolate(messages[locale][key] ?? en[key], args[0] as InterpolationValues | undefined);
}

